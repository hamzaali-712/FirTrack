import { createHash, randomUUID } from "node:crypto";
import { Router } from "express";
import mongoose from "mongoose";
import { createAuthMiddleware } from "../auth/middleware.js";
import { ApiError } from "../errors/ApiError.js";
import { Exercise } from "../models/Exercise.js";
import { IdempotencyRecord } from "../models/IdempotencyRecord.js";
import { WorkoutPlan } from "../models/WorkoutPlan.js";

const UUID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const SORTS = new Set(["updated_desc", "updated_asc", "name_asc"]);

function validation(message, fieldErrors) {
  throw new ApiError(422, "VALIDATION_ERROR", message, { fieldErrors });
}

function objectId(value, field) {
  if (typeof value !== "string" || !/^[a-f\d]{24}$/i.test(value) || !mongoose.isValidObjectId(value)) {
    validation("One or more plan fields are invalid.", [{ field, message: "Must be a valid exercise ID." }]);
  }
  return value;
}

function plainObject(value, field) {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    validation("One or more plan fields are invalid.", [{ field, message: "Must be an object." }]);
  }
}

function stringValue(value, field, minimum, maximum) {
  if (typeof value !== "string" || value.trim().length < minimum || value.trim().length > maximum) {
    validation("One or more plan fields are invalid.", [
      { field, message: `Must contain ${minimum}-${maximum} characters.` },
    ]);
  }
  return value.trim();
}

function integerValue(value, field, minimum, maximum) {
  if (!Number.isInteger(value) || value < minimum || value > maximum) {
    validation("One or more plan fields are invalid.", [
      { field, message: `Must be an integer from ${minimum} to ${maximum}.` },
    ]);
  }
  return value;
}

function canonicalBody(body) {
  return JSON.stringify(body, Object.keys(body).sort());
}

async function validateDays(rawDays, { existingPlan = null } = {}) {
  if (!Array.isArray(rawDays) || rawDays.length < 1 || rawDays.length > 7) {
    validation("A plan must contain 1-7 workout days.", [
      { field: "days", message: "A plan must contain 1-7 workout days." },
    ]);
  }

  const exerciseIds = new Map();
  const days = [];
  for (let dayIndex = 0; dayIndex < rawDays.length; dayIndex += 1) {
    const rawDay = rawDays[dayIndex];
    plainObject(rawDay, `days.${dayIndex}`);
    const allowedDayKeys = new Set(["id", "label", "weekday", "exercises"]);
    if (Object.keys(rawDay).some((key) => !allowedDayKeys.has(key))) {
      validation("One or more plan fields are invalid.", [
        { field: `days.${dayIndex}`, message: "Contains unsupported fields." },
      ]);
    }
    const label = stringValue(rawDay.label, `days.${dayIndex}.label`, 1, 50);
    let weekday = null;
    if (rawDay.weekday !== undefined && rawDay.weekday !== null) {
      weekday = integerValue(rawDay.weekday, `days.${dayIndex}.weekday`, 0, 6);
    }
    if (!Array.isArray(rawDay.exercises) || rawDay.exercises.length > 20) {
      validation("Each plan day must contain 0-20 exercises.", [
        { field: `days.${dayIndex}.exercises`, message: "Must contain 0-20 exercises." },
      ]);
    }

    let dayId;
    if (rawDay.id !== undefined) {
      if (!existingPlan) {
        validation("Creation payloads cannot supply server IDs.", [
          { field: `days.${dayIndex}.id`, message: "Day IDs are generated by the server." },
        ]);
      }
      dayId = objectId(rawDay.id, `days.${dayIndex}.id`);
      const existingDay = existingPlan.days.find((day) => day._id.toString() === dayId);
      if (!existingDay) {
        validation("The plan contains an unknown or foreign nested ID.", [
          { field: `days.${dayIndex}.id`, message: "Unknown day ID." },
        ]);
      }
    } else {
      dayId = new mongoose.Types.ObjectId();
    }

    const exercises = [];
    const positions = new Set();
    for (let exerciseIndex = 0; exerciseIndex < rawDay.exercises.length; exerciseIndex += 1) {
      const rawExercise = rawDay.exercises[exerciseIndex];
      plainObject(rawExercise, `days.${dayIndex}.exercises.${exerciseIndex}`);
      const allowedKeys = new Set([
        "id",
        "exerciseId",
        "position",
        "targetSets",
        "targetReps",
        "targetDurationSec",
        "targetWeightKg",
      ]);
      if (Object.keys(rawExercise).some((key) => !allowedKeys.has(key))) {
        validation("One or more plan fields are invalid.", [
          { field: `days.${dayIndex}.exercises.${exerciseIndex}`, message: "Contains unsupported fields." },
        ]);
      }
      const exerciseId = objectId(
        rawExercise.exerciseId,
        `days.${dayIndex}.exercises.${exerciseIndex}.exerciseId`,
      );
      const position = integerValue(
        rawExercise.position,
        `days.${dayIndex}.exercises.${exerciseIndex}.position`,
        0,
        19,
      );
      if (positions.has(position)) {
        validation("Exercise positions must be unique.", [
          { field: `days.${dayIndex}.exercises.${exerciseIndex}.position`, message: "Duplicate position." },
        ]);
      }
      positions.add(position);
      const targetSets = integerValue(
        rawExercise.targetSets,
        `days.${dayIndex}.exercises.${exerciseIndex}.targetSets`,
        1,
        12,
      );

      let entryId;
      if (rawExercise.id !== undefined) {
        if (!existingPlan) {
          validation("Creation payloads cannot supply server IDs.", [
            { field: `days.${dayIndex}.exercises.${exerciseIndex}.id`, message: "Exercise entry IDs are generated by the server." },
          ]);
        }
        entryId = objectId(rawExercise.id, `days.${dayIndex}.exercises.${exerciseIndex}.id`);
        const existingDay = existingPlan.days.find((day) => day._id.toString() === dayId);
        const existingEntry = existingDay?.exercises.find((entry) => entry._id.toString() === entryId);
        if (!existingEntry) {
          validation("The plan contains an unknown or foreign nested ID.", [
            { field: `days.${dayIndex}.exercises.${exerciseIndex}.id`, message: "Unknown exercise entry ID." },
          ]);
        }
        if (existingEntry.exerciseId.toString() !== exerciseId) {
          validation("An existing plan exercise cannot change its catalog exercise ID.", [
            { field: `days.${dayIndex}.exercises.${exerciseIndex}.exerciseId`, message: "Remove and recreate to swap exercises." },
          ]);
        }
      } else {
        entryId = new mongoose.Types.ObjectId();
      }

      if (exerciseIds.has(exerciseId)) exerciseIds.set(exerciseId, exerciseIds.get(exerciseId) + 1);
      else exerciseIds.set(exerciseId, 1);

      exercises.push({
        _id: entryId,
        exerciseId: new mongoose.Types.ObjectId(exerciseId),
        position,
        targetSets,
        targetReps: rawExercise.targetReps ?? null,
        targetDurationSec: rawExercise.targetDurationSec ?? null,
        targetWeightKg: rawExercise.targetWeightKg ?? null,
      });
    }

    const positionsSorted = [...positions].sort((a, b) => a - b);
    if (positionsSorted.some((position, index) => position !== index)) {
      validation("Exercise positions must be contiguous.", [
        { field: `days.${dayIndex}.exercises`, message: "Positions must be 0..n-1." },
      ]);
    }

    exercises.sort((a, b) => a.position - b.position);
    days.push({
      _id: dayId,
      label,
      weekday,
      exercises,
    });
  }

  const exercises = await Exercise.find({
    _id: { $in: [...exerciseIds.keys()].map((id) => new mongoose.Types.ObjectId(id)) },
    isActive: true,
  }).lean();
  if (exercises.length !== exerciseIds.size) {
    validation("One or more catalog exercises are unavailable.", [
      { field: "days.exercises.exerciseId", message: "Unknown or inactive exercise." },
    ]);
  }
  const exerciseById = new Map(exercises.map((exercise) => [exercise._id.toString(), exercise]));

  for (const day of days) {
    for (const entry of day.exercises) {
      const catalogExercise = exerciseById.get(entry.exerciseId.toString());
      const trackingType = catalogExercise.trackingType;
      if (trackingType === "duration") {
        if (entry.targetReps !== null || entry.targetWeightKg !== null) {
          validation("Duration exercises only accept targetDurationSec.", [
            { field: "targetDurationSec", message: "Reps and weight must be null." },
          ]);
        }
        integerValue(entry.targetDurationSec, "targetDurationSec", 1, 7200);
      } else {
        if (entry.targetDurationSec !== null) {
          validation("Rep-based exercises cannot set targetDurationSec.", [
            { field: "targetDurationSec", message: "Must be null." },
          ]);
        }
        integerValue(entry.targetReps, "targetReps", 1, 100);
        if (trackingType === "reps_only") {
          if (entry.targetWeightKg !== null) {
            validation("Reps-only exercises cannot set targetWeightKg.", [
              { field: "targetWeightKg", message: "Must be null." },
            ]);
          }
        } else if (entry.targetWeightKg !== null) {
          const weight = entry.targetWeightKg;
          if (typeof weight !== "number" || !Number.isFinite(weight) || weight < 0 || weight > 500) {
            validation("Target weight is outside the supported range.", [
              { field: "targetWeightKg", message: "Must be from 0 to 500 kg." },
            ]);
          }
        }
      }
    }
  }
  return days;
}

function toPlan(plan) {
  return {
    id: plan._id.toString(),
    name: plan.name,
    description: plan.description,
    days: plan.days.map((day) => ({
      id: day._id.toString(),
      label: day.label,
      weekday: day.weekday,
      exercises: day.exercises
        .sort((a, b) => a.position - b.position)
        .map((entry) => ({
          id: entry._id.toString(),
          exerciseId: entry.exerciseId.toString(),
          position: entry.position,
          targetSets: entry.targetSets,
          targetReps: entry.targetReps,
          targetDurationSec: entry.targetDurationSec,
          targetWeightKg: entry.targetWeightKg,
        })),
    })),
    createdAt: plan.createdAt.toISOString(),
    updatedAt: plan.updatedAt.toISOString(),
    version: plan.version,
  };
}

function canonicalizeValidatedPlan(body) {
  return JSON.stringify({
    name: body.name,
    description: body.description ?? "",
    days: body.days.map((day) => ({
      label: day.label,
      weekday: day.weekday,
      exercises: day.exercises.map((entry) => ({
        exerciseId: entry.exerciseId.toString(),
        position: entry.position,
        targetSets: entry.targetSets,
        targetReps: entry.targetReps,
        targetDurationSec: entry.targetDurationSec,
        targetWeightKg: entry.targetWeightKg,
      })),
    })),
  });
}

export function createPlanRouter(config) {
  const router = Router();
  const { requireCsrf, requireSession } = createAuthMiddleware(config);

  router.get("/", requireSession, async (req, res) => {
    const page = Number(req.query.page ?? 1);
    const limit = Number(req.query.limit ?? 20);
    const sort = req.query.sort ?? "updated_desc";
    if (!Number.isSafeInteger(page) || page < 1 || page > 10000 ||
        !Number.isSafeInteger(limit) || limit < 1 || limit > 50 ||
        !SORTS.has(sort) ||
        Object.keys(req.query).some((key) => !["page", "limit", "sort"].includes(key))) {
      throw new ApiError(400, "INVALID_QUERY", "One or more plan query parameters are invalid.");
    }
    const sortForQuery =
      sort === "name_asc" ? { name: 1, _id: 1 } :
      sort === "updated_asc" ? { updatedAt: 1, _id: 1 } :
      { updatedAt: -1, _id: 1 };
    const filter = { userId: req.authUserId, archivedAt: null };
    const [total, plans] = await Promise.all([
      WorkoutPlan.countDocuments(filter),
      WorkoutPlan.find(filter).sort(sortForQuery).skip((page - 1) * limit).limit(limit).lean(),
    ]);
    res.setHeader("Cache-Control", "private, no-store");
    res.status(200).json({
      data: plans.map((plan) => ({
        id: plan._id.toString(),
        name: plan.name,
        dayCount: plan.days.length,
        updatedAt: plan.updatedAt.toISOString(),
        version: plan.version,
      })),
      meta: {
        page,
        limit,
        total,
        totalPages: total === 0 ? 0 : Math.ceil(total / limit),
        hasNextPage: (page - 1) * limit + plans.length < total,
      },
    });
  });

  router.post("/", requireSession, requireCsrf, async (req, res) => {
    plainObject(req.body, "body");
    const key = req.get("idempotency-key");
    if (typeof key !== "string" || !UUID_PATTERN.test(key)) {
      throw new ApiError(400, "INVALID_IDEMPOTENCY_KEY", "A valid UUID Idempotency-Key is required.");
    }
    const allowedCreateKeys = new Set(["name", "description", "days"]);
    if (Object.keys(req.body).some((field) => !allowedCreateKeys.has(field))) {
      validation("Server-owned or unsupported plan fields are not allowed.", [
        { field: "body", message: "Contains unsupported fields." },
      ]);
    }
    const name = stringValue(req.body.name, "name", 2, 80);
    let description = "";
    if (req.body.description !== undefined) {
      if (typeof req.body.description !== "string" || req.body.description.length > 500) {
        validation("The plan description is invalid.", [
          { field: "description", message: "Must be at most 500 characters." },
        ]);
      }
      description = req.body.description.trim();
    }
    const days = await validateDays(req.body.days);
    const payloadHash = createHash("sha256")
      .update(canonicalizeValidatedPlan({ name, description, days }))
      .digest("hex");

    const session = await mongoose.startSession();
    try {
      let replay;
      await session.withTransaction(async () => {
        const existing = await IdempotencyRecord.findOne({
          userId: req.authUserId,
          method: "POST",
          routeKey: "plans",
          key,
        }).session(session);
        if (existing) {
          if (existing.payloadHash !== payloadHash) {
            throw new ApiError(409, "IDEMPOTENCY_KEY_REUSED", "This idempotency key is already used for a different request.");
          }
          replay = existing;
          return;
        }

        const plan = await WorkoutPlan.create([{
          userId: req.authUserId,
          name,
          description,
          days,
          version: 1,
          archivedAt: null,
        }], { session }).then((created) => created[0]);
        const responseBody = { data: toPlan(plan) };
        await IdempotencyRecord.create([{
          userId: req.authUserId,
          method: "POST",
          routeKey: "plans",
          key,
          payloadHash,
          statusCode: 201,
          responseBody,
          resourceId: plan._id,
          expiresAt: new Date(Date.now() + 24 * 60 * 60 * 1000),
        }], { session });
        replay = { statusCode: 201, responseBody, resourceId: plan._id };
        res.setHeader("Location", `/api/v1/plans/${plan._id.toString()}`);
      });

      res.setHeader("Cache-Control", "private, no-store");
      res.status(replay.statusCode).json(replay.responseBody);
    } finally {
      await session.endSession();
    }
  });

  router.get("/:planId", requireSession, async (req, res) => {
    if (!/^[a-f\d]{24}$/i.test(req.params.planId)) {
      throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    }
    const plan = await WorkoutPlan.findOne({
      _id: req.params.planId,
      userId: req.authUserId,
      archivedAt: null,
    }).lean();
    if (!plan) throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    res.setHeader("Cache-Control", "private, no-store");
    res.status(200).json({ data: toPlan(plan) });
  });

  router.patch("/:planId", requireSession, requireCsrf, async (req, res) => {
    if (!/^[a-f\d]{24}$/i.test(req.params.planId)) {
      throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    }
    plainObject(req.body, "body");
    if (!Object.prototype.hasOwnProperty.call(req.body, "version")) {
      validation("Plan version is required.", [{ field: "version", message: "Required." }]);
    }
    integerValue(req.body.version, "version", 1, Number.MAX_SAFE_INTEGER);
    const allowedPatchKeys = new Set(["version", "name", "description", "days"]);
    if (Object.keys(req.body).some((key) => !allowedPatchKeys.has(key))) {
      validation("Server-owned or unsupported plan fields are not allowed.", [
        { field: "body", message: "Contains unsupported fields." },
      ]);
    }
    if (!["name", "description", "days"].some((key) => Object.prototype.hasOwnProperty.call(req.body, key))) {
      validation("At least one mutable plan field is required.", [
        { field: "body", message: "Provide name, description, or days." },
      ]);
    }

    const plan = await WorkoutPlan.findOne({
      _id: req.params.planId,
      userId: req.authUserId,
      archivedAt: null,
    });
    if (!plan) throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    if (plan.version !== req.body.version) {
      throw new ApiError(409, "VERSION_CONFLICT", "The plan has changed.", {
        fieldErrors: [{ field: "version", message: `Current version is ${plan.version}.` }],
      });
    }

    const changes = {};
    if (Object.prototype.hasOwnProperty.call(req.body, "name")) {
      changes.name = stringValue(req.body.name, "name", 2, 80);
    }
    if (Object.prototype.hasOwnProperty.call(req.body, "description")) {
      if (typeof req.body.description !== "string" || req.body.description.length > 500) {
        validation("The plan description is invalid.", [
          { field: "description", message: "Must be at most 500 characters." },
        ]);
      }
      changes.description = req.body.description.trim();
    }
    if (Object.prototype.hasOwnProperty.call(req.body, "days")) {
      changes.days = await validateDays(req.body.days, { existingPlan: plan });
    }

    const updated = await WorkoutPlan.findOneAndUpdate(
      {
        _id: plan._id,
        userId: req.authUserId,
        archivedAt: null,
        version: req.body.version,
      },
      { $set: changes, $inc: { version: 1 } },
      { returnDocument: "after", runValidators: true },
    );
    if (!updated) {
      throw new ApiError(409, "VERSION_CONFLICT", "The plan has changed.", {
        fieldErrors: [{ field: "version", message: "Refetch the current plan." }],
      });
    }
    res.setHeader("Cache-Control", "private, no-store");
    res.status(200).json({ data: toPlan(updated) });
  });

  router.delete("/:planId", requireSession, requireCsrf, async (req, res) => {
    if (!/^[a-f\d]{24}$/i.test(req.params.planId)) {
      throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    }
    const plan = await WorkoutPlan.findOne({
      _id: req.params.planId,
      userId: req.authUserId,
    });
    if (!plan) throw new ApiError(404, "RESOURCE_NOT_FOUND", "The requested plan was not found.");
    if (!plan.archivedAt) {
      plan.archivedAt = new Date();
      await plan.save();
    }
    res.setHeader("Cache-Control", "private, no-store");
    res.status(204).send();
  });

  return router;
}
